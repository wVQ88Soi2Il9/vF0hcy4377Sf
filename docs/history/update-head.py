#!/usr/bin/env python3
"""重新產生 `head.md`，並檢查 `docs/history/` 的內部一致性。

僅使用標準函式庫。解析與檢查規則在 `plan_parse.py`；本檔只負責 `head.md` 的呈現與 CLI。

    python docs/history/update-head.py          # 手動執行，結果印在 stdout
    python docs/history/update-head.py --check  # 只檢查，不寫 head.md
    python docs/history/update-head.py --hook   # PostToolUse hook（從 stdin 讀 hook JSON）

`head.md` 是計畫檔的純函式（沒有時間戳），沒有變動時重跑不會產生差異。

結束碼：0 乾淨 · 1 有衝突（手動） · 2 有衝突（--hook，讓 agent 看到 stderr）。
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from plan_parse import (
    HERE,
    LIVE_STATUSES,
    NON_PLAN_FILES,
    ROOT_DISPLAY,
    Conflict,
    Plan,
    blockers,
    collect,
    display_state,
    force_utf8_stdio,
    format_conflicts,
    item_index,
)

HEAD = HERE / "head.md"

# HEAD 是第一個非空分類裡序號最大的計畫。
HEAD_PREFERENCE = ("in-progress", "draft", "done")


def pick_head(plans: list[Plan]) -> Plan | None:
    for status in HEAD_PREFERENCE:
        bucket = [p for p in plans if p.status == status]
        if bucket:
            return max(bucket, key=lambda p: p.seq)
    return None


def _link(p: Plan) -> str:
    return f"[{p.stem}](./{p.name})"


def _remaining(p: Plan) -> str:
    line = f"待辦剩 {p.open_items}/{p.total}"
    if p.handoff_count:
        line += f"，已移交 {p.handoff_count}"
    return line


def render_open_items(plans: list[Plan]) -> list[str]:
    """每個開著的格子一行 —— 不開任何計畫檔就能回答「哪份計畫、哪一格管這件事」。"""
    index = item_index(plans)
    live = sorted((p for p in plans if p.status in LIVE_STATUSES), key=lambda p: p.seq, reverse=True)
    rows = [it for p in live for it in p.items if it.is_open]

    out = ["", "## 現在開著的（逐格）", ""]
    if not rows:
        return out + ["（沒有開著的項目）"]
    for it in rows:
        line = f"- `{it.addr}` · **{display_state(it, index)}**"
        if held := blockers(it, index):
            line += "（等 " + "、".join(f"`{a}`" for a in held) + "）"
        out.append(f"{line} — {it.title}")
    out += [
        "",
        f"> 要做某一格：`python3 {ROOT_DISPLAY}/plan-item.py {rows[0].addr}`",
        "> —— 只回那一格的正文與它的依據，不必讀整份計畫。",
    ]
    return out


def render_head(plans: list[Plan], conflicts: list[Conflict]) -> str:
    out = [
        "# Plan history — HEAD",
        "",
        f"<!-- Generated by {ROOT_DISPLAY}/update-head.py — do not hand-edit. -->",
        "",
        "## 目前使用中",
        "",
    ]

    head = pick_head(plans)
    if head is None:
        out.append("（尚無任何計畫）")
    else:
        line = f"{_link(head)} — `{head.status}`"
        if head.status == "in-progress":
            line += f"，{_remaining(head)}"
        out.append(line)

    out += render_open_items(plans)
    out += ["", "## draft / in-progress（序號降序）", ""]

    live = sorted((p for p in plans if p.status in LIVE_STATUSES), key=lambda p: p.seq, reverse=True)
    if not live:
        out.append("（無）")
    for p in live:
        line = f"- **{p.seq}** {_link(p)} — `{p.status}`"
        if p.status == "in-progress":
            line += f"，{_remaining(p)}"
        out.append(line)

    if conflicts:
        out += [
            "",
            f"> ⚠ 有 {len(conflicts)} 項一致性衝突未解決。",
            f"> 執行 `python3 {ROOT_DISPLAY}/update-head.py` 看明細。",
        ]

    return "\n".join(out) + "\n"


def hook_should_run() -> bool:
    """stdin 上的 PostToolUse payload 是否動到了計畫檔。"""
    try:
        payload = json.load(sys.stdin)
    except (json.JSONDecodeError, ValueError):
        return False
    tool_input = payload.get("tool_input") or {}
    raw = tool_input.get("file_path") or tool_input.get("notebook_path") or ""
    if not raw:
        return False
    try:
        path = Path(raw).resolve()
    except OSError:
        return False
    return path.parent == HERE and path.name not in NON_PLAN_FILES and path.suffix == ".md"


def main() -> int:
    force_utf8_stdio()
    args = set(sys.argv[1:])
    hook = "--hook" in args
    check_only = "--check" in args

    if hook and not hook_should_run():
        return 0

    report = collect()

    if not check_only:
        rendered = render_head(report.plans, report.errors)
        if not HEAD.exists() or HEAD.read_text(encoding="utf-8") != rendered:
            HEAD.write_text(rendered, encoding="utf-8")
            if not hook:
                print(f"[plan-history] head.md 已更新（{len(report.plans)} 份計畫）")
        elif not hook:
            print(f"[plan-history] head.md 已是最新（{len(report.plans)} 份計畫）")

    if not report.conflicts:
        return 0

    # 警告只印出，不讓執行失敗：它要的是判斷（拆格、縮短檔頭），強迫處理只會逼人把它靜音。
    text = format_conflicts(report.conflicts)
    if hook:
        print(text, file=sys.stderr)
        return 2 if report.errors else 0
    print(text)
    return 1 if report.errors else 0


if __name__ == "__main__":
    sys.exit(main())
